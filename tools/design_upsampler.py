#!/usr/bin/env python3
"""Design the 16 kHz -> 48 kHz upsampler the voice path runs, and emit it as C.

omni's proto asks for "one raw Opus packet: mono, 48 kHz, 20 ms". The microphone runs
at 16 kHz, so the kit upsamples by 3 before encoding. Encoding at 16 kHz instead was
tried against staging omni, and so was upsampling by linear interpolation: both made
the speech recogniser hallucinate a word ("Subscribe") into a clean sentence, three
runs out of three. The images a cheap upsampler leaves above 8 kHz are the cause —
audio band-limited to 8 kHz and upsampled properly transcribes cleanly.

So: zero-stuff by 3, windowed-sinc low-pass just under the 8 kHz a 16 kHz microphone
can carry, Blackman window, 48 taps, Q15, split into three 16-tap phases. This is the
exact filter that was validated against omni; change it and validate again.

    python3 tools/design_upsampler.py > main/generated/voice_upsampler.h
"""
import math

L, TAPS, FC_HZ, OUT_HZ = 3, 48, 7600.0, 48000.0
fc = FC_HZ / OUT_HZ
h = []
for n in range(TAPS):
    m = n - (TAPS - 1) / 2
    s = 2 * fc if m == 0 else math.sin(2 * math.pi * fc * m) / (math.pi * m)
    w = 0.42 - 0.5 * math.cos(2 * math.pi * n / (TAPS - 1)) + 0.08 * math.cos(4 * math.pi * n / (TAPS - 1))
    h.append(s * w)
g = sum(h)
q15 = [max(-32768, min(32767, round(L * v / g * 32768))) for v in h]
phases = [q15[p::L] for p in range(L)]

print("/* GENERATED by tools/design_upsampler.py — do not edit. */")
print("#pragma once")
print("#include <stdint.h>")
print(f"/* 16 kHz -> 48 kHz: zero-stuff by {L}, Blackman-windowed sinc at {int(FC_HZ)} Hz, {TAPS} taps, Q15.")
print(" * Phase p of output k*3+p is the dot product of phase[p] with the input history,")
print(" * newest sample first. Validated against staging omni's speech recogniser. */")
print(f"#define VOICE_UP_L      {L}")
print(f"#define VOICE_UP_PHASE  {TAPS // L}")
print(f"static const int16_t voice_up_phase[{L}][{TAPS // L}] = {{")
for p in phases:
    print("    { " + ", ".join(str(c) for c in p) + " },")
print("};")
