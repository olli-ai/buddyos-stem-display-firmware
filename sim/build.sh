#!/usr/bin/env bash
# Build and run the headless simulator.
#
#   bash sim/build.sh --serve        # watch it in a browser at localhost:8080
#   bash sim/build.sh sim/frames     # or dump PPM frames
#
# It needs a host compiler, through $CC (default `cc`). On this Mac `cc` is the
# xcode-select wrapper, which is broken — it cannot load libxcodebuildLoader.dylib —
# while the compiler behind it works, so name clang and its SDK directly:
#
#   CC=/Applications/Xcode.app/Contents/Developer/Toolchains/XcodeDefault.xctoolchain/usr/bin/clang \
#   AR=/Applications/Xcode.app/Contents/Developer/Toolchains/XcodeDefault.xctoolchain/usr/bin/ar \
#   SYSROOT=/Applications/Xcode.app/Contents/Developer/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk \
#   bash sim/build.sh --serve
#
# A container also works and needs neither — but one run of it cost 5.8 GB of Docker
# disk on this machine, so it is the fallback, not the way:
#
#   docker run --rm -p 8080:8080 -v "$PWD":/fw -w /fw espressif/idf:v5.2.2 \
#       bash sim/build.sh --serve
#
# LVGL is cloned on first run and kept in sim/lvgl (gitignored).
set -euo pipefail
cd "$(dirname "$0")/.."
MODE=${1:-sim/frames}
CC=${CC:-cc}
# `ar` is the same broken wrapper as `cc` on this Mac, so it takes the same treatment.
AR=${AR:-ar}
SYSROOT_FLAG=${SYSROOT:+-isysroot $SYSROOT}

# LVGL lives in components/ because the firmware build needs it there too (it is
# vendored rather than fetched: idf 5.2.2's component manager cannot parse a `&&`
# in a dependency manifest, and fails while merely listing registry versions).
# One checkout, both builds.
if [ ! -d components/lvgl ]; then
  git clone --depth 1 --branch release/v9.2 https://github.com/lvgl/lvgl.git components/lvgl
fi

# lv_conf.h from LVGL's own template, so the simulator tracks whatever the version
# in sim/lvgl expects rather than a copy that rots. Colour depth matches the panel.
if [ ! -f sim/lv_conf.h ]; then
  # In one pass and into a new file: BSD sed's -i is not GNU sed's, and this script
  # now runs on the host as well as in a container.
  sed -e '0,/#if 0/s//#if 1/' \
      -e 's/^#define LV_COLOR_DEPTH .*/#define LV_COLOR_DEPTH 16/' \
      -e 's/^#define LV_USE_LOG .*/#define LV_USE_LOG 1/' \
      components/lvgl/lv_conf_template.h > sim/lv_conf.h
  # LVGL's default 64 KB heap is left alone ON PURPOSE. An earlier renderer put a
  # transform on the face container, which makes LVGL draw it through a 240x240
  # layer — 115 KB at RGB565 — and with 64 KB the allocation fails and the refresh
  # spins forever. That was found here rather than on hardware. The renderer now
  # composes the head per sprite, so if this still draws at the default heap, the
  # device can afford it too.
fi

[ "$MODE" = "--serve" ] || mkdir -p "$MODE"

# sdkconfig.h, which board_pins.h includes and the host has no idf.py to write.
# Empty is the right content: every CONFIG_ the face reads is a feature of a board
# that is not here, and an undefined one is 0 to the preprocessor — which lands on
# the S3's 240x240, the geometry this simulator renders.
if [ ! -f sim/sdkconfig.h ]; then
  printf '/* Generated by sim/build.sh. No board, so no CONFIG_. */\n#pragma once\n' > sim/sdkconfig.h
fi

# LVGL is ~600 files; building it once into a static library turns a rebuild of our
# own three files from eight minutes into seconds. Rebuilt when lv_conf.h changes.
if [ ! -f sim/liblvgl.a ] || [ sim/lv_conf.h -nt sim/liblvgl.a ]; then
  echo "building liblvgl.a (once)..."
  rm -rf sim/objs && mkdir -p sim/objs
  # No mapfile (macOS ships bash 3.2) and no nproc (that is Linux's): find feeds
  # xargs directly, and the core count comes from whichever tool this OS has.
  JOBS=$( (nproc || sysctl -n hw.ncpu) 2>/dev/null || echo 4)
  find components/lvgl/src -name '*.c' -print0 | xargs -0 -P "$JOBS" -I{} sh -c \
    "$CC $SYSROOT_FLAG -std=gnu11 -O1 -w -DLV_CONF_INCLUDE_SIMPLE -I sim -I components/lvgl -c \"\$1\" -o \"sim/objs/\$(echo \"\$1\" | tr / _).o\"" _ {}
  "$AR" rcs sim/liblvgl.a sim/objs/*.o
fi

$CC $SYSROOT_FLAG -std=gnu11 -O1 -w \
    -DLV_CONF_INCLUDE_SIMPLE \
    -I sim -I components/lvgl -I main -I main/generated \
    sim/sim_main.c sim/sim_server.c main/face_view.c main/face_motion.c main/face_lipsync.c main/generated/face_assets_240.c \
    sim/liblvgl.a -lm -o sim/facesim
# The second argument must not be passed through empty: the simulator sees an argv[2]
# of "", takes atoi("") = 0 for a port, and binds an ephemeral one — so the README's
# own "open localhost:8080" was wrong for anyone who ran it without a port.
exec ./sim/facesim "$MODE" "${2:-8080}"
